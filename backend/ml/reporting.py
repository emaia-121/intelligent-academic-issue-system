"""
Report generation: model_comparison.csv and training_report.md.
Kept separate from the training pipeline so report formatting can change
without touching training logic.
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd

from evaluation import confusion_matrix_to_dataframe


def write_model_comparison_csv(all_results: dict[str, dict], output_path: Path) -> pd.DataFrame:
    """Writes Model,Accuracy,Precision,Recall,F1 (macro-averaged) for every
    trained model, sorted best-first by F1. Returns the DataFrame too so the
    caller can reuse it for model selection / the markdown report."""
    rows = [
        {
            "Model": name,
            "Accuracy": res["accuracy"],
            "Precision": res["precision_macro"],
            "Recall": res["recall_macro"],
            "F1": res["f1_macro"],
        }
        for name, res in all_results.items()
    ]
    df = pd.DataFrame(rows).sort_values("F1", ascending=False).reset_index(drop=True)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(output_path, index=False)
    return df


def _fmt_pct(value: float) -> str:
    return f"{value * 100:.2f}%"


def _markdown_table(df: pd.DataFrame) -> str:
    return df.to_markdown(index=False)


def write_training_report_md(
    *,
    output_path: Path,
    dataset_path: Path,
    dataset_size: int,
    class_counts: pd.Series,
    vectorizer_search_results: pd.DataFrame,
    chosen_vectorizer_config: dict,
    comparison_df: pd.DataFrame,
    all_results: dict[str, dict],
    class_names: list[str],
    best_model_name: str,
    export_dir: Path,
    train_size: int,
    test_size: int,
) -> None:
    """Writes the full maintainer-facing training report described in the
    task: dataset, preprocessing, feature extraction, models trained,
    evaluation metrics, selected model and why, export locations."""

    best_row = comparison_df.iloc[0]
    lines: list[str] = []

    lines.append("# Academic Issue Classifier -- Training Report\n")
    lines.append(
        "This report documents how `ml/train_classifier.py` produced the exported "
        "classifier in `ml/models/`. It is written for a developer who did not run "
        "the training themselves and needs to understand or maintain the pipeline.\n"
    )

    # -- Dataset -----------------------------------------------------------
    lines.append("## 1. Dataset\n")
    lines.append(f"- Source file: `{dataset_path.relative_to(dataset_path.parents[2])}`")
    lines.append(f"- Total labelled examples: **{dataset_size}**")
    lines.append(f"- Number of categories: **{len(class_names)}** (fixed list, no categories invented)")
    lines.append(
        "- Generated by `ml/generate_dataset.py`: a template-and-slot synthetic generator "
        "(20-30 hand-authored sentence skeletons per category, combined with randomized "
        "course codes, sessions, levels, departments, optional tone openers/closers, and "
        "light informal text substitutions). All 1,500 rows are verified unique strings -- "
        "duplicates are rejected and regenerated at creation time."
    )
    lines.append("\n**Class distribution:**\n")
    dist_df = class_counts.rename_axis("Category").reset_index(name="Count")
    lines.append(_markdown_table(dist_df))
    lines.append("")

    # -- Train/test split ---------------------------------------------------
    lines.append("## 2. Train/Test Split\n")
    lines.append(
        "- Target ratio: 80/20, stratified by category.\n"
        "- **Grouped by sentence template within each category**, not a plain row-level "
        "split: `generate_dataset.py` records which of the ~20-30 hand-authored skeletons "
        "produced each row (`template_id`), and `train_classifier.py::split_dataset` splits "
        "each category's *templates* 80/20 (`sklearn.model_selection.train_test_split(..., "
        "random_state=42)` applied to the template ID list) before assigning every row to "
        "whichever side its template landed on.\n"
        "- This was a deliberate change from a naive per-row stratified split. A first pass "
        "using a plain row-level stratified split let the same skeleton (e.g. *\"My {code} "
        "result has not appeared since {session}.\"*) appear on both sides with only a "
        "course code swapped, and every model scored 99-100% test accuracy -- a sign the "
        "test set wasn't actually novel to the model, just superficially reworded. Grouping "
        "by template means every test-set sentence uses phrasing the model never saw during "
        "training, which is what the task means by \"the classifier should learn concepts "
        "rather than memorize phrases.\" The resulting scores (Section 6) are lower but "
        "meaningfully honest.\n"
        f"- Training examples: **{train_size}**\n"
        f"- Test examples: **{test_size}**\n"
        f"- `random_state=42` is fixed throughout the pipeline (split, cross-validation, "
        f"and every model that accepts a `random_state`) so results are reproducible."
    )
    lines.append("")

    # -- Preprocessing --------------------------------------------------------
    lines.append("## 3. Preprocessing\n")
    lines.append(
        "Implemented in `ml/preprocessing.py`. Applied identically to every example "
        "before vectorization:\n"
    )
    lines.append(
        "1. **Course-code normalization** (before lowercasing): `\"CSC 311\"` -> "
        "`\"CSC311\"`, so spaced and unspaced course-code mentions always tokenize "
        "identically instead of the spaced form splitting into two diluted tokens.\n"
        "2. **Lowercasing**: case carries no classification signal here and keeps the "
        "vocabulary compact.\n"
        "3. **Whitespace normalization**: repeated spaces/newlines collapse to one space; "
        "leading/trailing whitespace stripped.\n"
        "4. **No stemming/lemmatization**: course codes and domain abbreviations "
        "(GST, NYSC, JAMB, CGPA, CSC311, ...) are exactly the signal the classifier "
        "should keep intact, and stemming risks mangling them or collapsing meaningfully "
        "distinct words. Skipped per the task's own guidance to avoid aggressive "
        "stemming unless justified -- no evaluation here showed a benefit.\n"
        "5. **Stopword removal**: not hardcoded. Evaluated explicitly (see Section 4) "
        "as part of the TF-IDF configuration search rather than assumed."
    )
    lines.append("")

    # -- Feature extraction --------------------------------------------------
    lines.append("## 4. Feature Extraction (TF-IDF)\n")
    lines.append(
        "`ml/evaluation.py::select_best_vectorizer_config` cross-validates every "
        "candidate TF-IDF configuration using a fixed Logistic Regression probe model "
        "and 5-fold stratified cross-validation, scored on mean macro-F1 -- all on the "
        "**training split only**, so the held-out test set never influences this choice. "
        "Candidates varied unigrams vs. unigrams+bigrams, stopword removal on/off, and "
        "`min_df` of 2 vs. 3 (`max_df` fixed at 0.9).\n"
    )
    display_grid = vectorizer_search_results.copy()
    display_grid["ngram_range"] = display_grid["ngram_range"].astype(str)
    display_grid["stop_words"] = display_grid["stop_words"].fillna("None").astype(str)
    display_grid["mean_cv_f1_macro"] = display_grid["mean_cv_f1_macro"].round(4)
    display_grid["std_cv_f1_macro"] = display_grid["std_cv_f1_macro"].round(4)
    lines.append(_markdown_table(display_grid))
    lines.append("")
    lines.append(
        f"**Chosen configuration:** `ngram_range={chosen_vectorizer_config['ngram_range']}`, "
        f"`stop_words={chosen_vectorizer_config['stop_words']}`, "
        f"`min_df={chosen_vectorizer_config['min_df']}`, "
        f"`max_df={chosen_vectorizer_config['max_df']}`, `sublinear_tf=True`."
    )
    lines.append("")

    # -- Models ---------------------------------------------------------------
    lines.append("## 5. Models Trained\n")
    lines.append(
        "All four required classical models, trained on the same TF-IDF features "
        "(see `ml/model_config.py` for exact hyperparameters and the reasoning behind "
        "each):\n"
        "1. Multinomial Naive Bayes\n"
        "2. Logistic Regression\n"
        "3. Linear Support Vector Machine (LinearSVC)\n"
        "4. Random Forest\n"
    )

    # -- Evaluation -------------------------------------------------------------
    lines.append("## 6. Evaluation\n")
    lines.append(
        "All metrics below are computed on the held-out test set only "
        "(never seen during training or vectorizer selection). Precision/Recall/F1 are "
        "macro-averaged across all 12 categories, treating every category equally "
        "regardless of size.\n"
    )
    display_comparison = comparison_df.copy()
    for col in ["Accuracy", "Precision", "Recall", "F1"]:
        display_comparison[col] = display_comparison[col].round(4)
    lines.append(_markdown_table(display_comparison))
    lines.append("")

    for name in comparison_df["Model"]:
        res = all_results[name]
        lines.append(f"### {name}\n")
        lines.append(f"- Accuracy: {_fmt_pct(res['accuracy'])}")
        lines.append(f"- Precision (macro): {_fmt_pct(res['precision_macro'])}")
        lines.append(f"- Recall (macro): {_fmt_pct(res['recall_macro'])}")
        lines.append(f"- F1 (macro): {_fmt_pct(res['f1_macro'])}\n")
        lines.append("**Classification report:**\n")
        lines.append("```")
        lines.append(res["classification_report_text"].rstrip())
        lines.append("```\n")
        lines.append("**Confusion matrix** (rows = true category, columns = predicted category):\n")
        cm_df = confusion_matrix_to_dataframe(res["confusion_matrix"], class_names)
        lines.append(_markdown_table(cm_df.reset_index().rename(columns={"index": "True \\ Pred"})))
        lines.append("")

    # -- Selection --------------------------------------------------------------
    lines.append("## 7. Selected Model\n")
    lines.append(f"**{best_model_name}** was selected automatically -- the pipeline sorts all four "
                  "models by macro-F1 on the test set and picks the top row; no model is "
                  "assumed best in advance.\n")
    lines.append(
        f"- Test accuracy: {_fmt_pct(best_row['Accuracy'])}\n"
        f"- Test macro precision: {_fmt_pct(best_row['Precision'])}\n"
        f"- Test macro recall: {_fmt_pct(best_row['Recall'])}\n"
        f"- Test macro F1: {_fmt_pct(best_row['F1'])}\n"
    )
    lines.append(
        "Macro-F1 was used as the ranking metric (rather than plain accuracy) because "
        "it weights every one of the 12 categories equally -- important for a routing "
        "system where a rarely-seen category being misclassified is just as costly as a "
        "common one being misclassified, even on this class-balanced dataset."
    )
    lines.append("")

    # -- Export -------------------------------------------------------------------
    lines.append("## 8. Export\n")
    lines.append(f"- Trained classifier: `{export_dir}/classifier.pkl` (joblib)")
    lines.append(f"- Fitted TF-IDF vectorizer: `{export_dir}/vectorizer.pkl` (joblib)")
    lines.append(f"- Category label list: `{export_dir}/label_classes.json`")
    lines.append(f"- Run metadata (chosen model, vectorizer config, dataset size, timestamp): `{export_dir}/metadata.json`")
    lines.append(
        "\nTo use the classifier later (not part of this task -- integration into Django "
        "views is intentionally out of scope), load both artifacts and apply the same "
        "preprocessing before vectorizing new text:\n"
    )
    lines.append("```python")
    lines.append("import joblib")
    lines.append("from ml.preprocessing import clean_text")
    lines.append("")
    lines.append("classifier = joblib.load('ml/models/classifier.pkl')")
    lines.append("vectorizer = joblib.load('ml/models/vectorizer.pkl')")
    lines.append("")
    lines.append("text = clean_text(raw_issue_description)")
    lines.append("predicted_category = classifier.predict(vectorizer.transform([text]))[0]")
    lines.append("```\n")

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(lines), encoding="utf-8")
